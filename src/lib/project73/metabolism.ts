import type { MetabolicSettings } from '../../types/project73';

/** Energy content of one kilogram of body-weight change, a common planning approximation. */
export const KCAL_PER_KG = 7700;
const WEEKS_PER_MONTH = 52.1775 / 12;

export interface MetabolicInput {
  sex: 'male' | 'female';
  age: number;
  heightCm: number;
  weightKg: number;
}

export const ACTIVITY_LEVELS = [
  { factor: 1.2, label: 'Zittend', detail: 'Kantoor- of computerwerk, nauwelijks extra beweging.' },
  { factor: 1.25, label: 'Zittend + dagelijks wandelen', detail: 'Zittend werk met wat wandelen of fietsen per dag.' },
  { factor: 1.375, label: 'Licht actief', detail: 'Zittend werk en 2–3 trainingen per week.' },
  { factor: 1.55, label: 'Matig actief', detail: 'Veel op de been of 4–5 trainingen per week.' },
  { factor: 1.725, label: 'Zeer actief', detail: 'Fysiek werk of dagelijks intensief sporten.' },
] as const;

export function round(value: number, step = 1) {
  return Math.round(value / step) * step;
}

/** Mifflin-St Jeor basal metabolic rate (kcal/day). */
export function mifflinStJeorBmr({ sex, age, heightCm, weightKg }: MetabolicInput) {
  const base = 10 * weightKg + 6.25 * heightCm - 5 * age;
  return base + (sex === 'male' ? 5 : -161);
}

export function totalDailyEnergyExpenditure(bmr: number, activityFactor: number) {
  return bmr * activityFactor;
}

export function weeksBetweenTimeframe(months: number) {
  return Math.max(1, months * WEEKS_PER_MONTH);
}

export function kgPerWeekFromDeficit(dailyDeficitKcal: number) {
  return (dailyDeficitKcal * 7) / KCAL_PER_KG;
}

export function deficitForKgPerWeek(kgPerWeek: number) {
  return (kgPerWeek * KCAL_PER_KG) / 7;
}

export interface TargetWarning {
  code: 'aggressive_deficit' | 'below_bmr' | 'below_minimum' | 'fast_rate' | 'slow_timeframe' | 'low_protein' | 'goal_reached' | 'override_differs';
  severity: 'info' | 'warning';
  message: string;
}

export interface Forecast {
  kgPerWeek: number;
  weeks: number | null;
  date: string | null;
}

export interface TargetRecommendation {
  bmr: number;
  tdee: number;
  maintenanceRange: [number, number];
  /** Suggested targets before user overrides. */
  suggested: { kcal: number; protein: number; carbs: number; fat: number; fiber: number };
  /** Targets in effect (overrides applied). */
  active: { kcal: number; protein: number; carbs: number; fat: number; fiber: number };
  vegetablesGrams: number;
  fruitGrams: number;
  dailyDeficit: number;
  expectedKgPerWeek: number;
  remainingKg: number;
  forecasts: { timeframe: Forecast; target: Forecast };
  warnings: TargetWarning[];
  assumptions: string[];
}

function addWeeks(date: string, weeks: number) {
  const value = new Date(`${date}T12:00:00`);
  value.setDate(value.getDate() + Math.round(weeks * 7));
  return value.toISOString().slice(0, 10);
}

export function forecastFor(remainingKg: number, kgPerWeek: number, fromDate: string): Forecast {
  if (remainingKg <= 0) return { kgPerWeek, weeks: 0, date: fromDate };
  if (kgPerWeek <= 0.01) return { kgPerWeek, weeks: null, date: null };
  const weeks = remainingKg / kgPerWeek;
  return { kgPerWeek, weeks, date: addWeeks(fromDate, weeks) };
}

export function minimumCalories(sex: 'male' | 'female') {
  return sex === 'male' ? 1500 : 1200;
}

const nl = (value: number, digits = 0) => value.toLocaleString('nl-NL', { minimumFractionDigits: digits, maximumFractionDigits: digits });

/**
 * Deterministic target calculation. Every number here is arithmetic on the profile; nothing is
 * generated by AI. Results are estimates and are labelled as such in the interface.
 */
export function recommendTargets(
  input: MetabolicInput & { goalWeightKg: number },
  settings: Pick<MetabolicSettings, 'activityFactor' | 'timeframeMonths' | 'pace' | 'desiredLossKgPerWeek' | 'overrides'>,
  today: string,
): TargetRecommendation {
  const bmr = mifflinStJeorBmr(input);
  const tdee = totalDailyEnergyExpenditure(bmr, settings.activityFactor);
  const remainingKg = Math.max(0, input.weightKg - input.goalWeightKg);
  const [minRate, maxRate] = settings.desiredLossKgPerWeek;
  const warnings: TargetWarning[] = [];

  const timeframeRate = remainingKg / weeksBetweenTimeframe(settings.timeframeMonths);
  // The "target" pace aims a little above the middle of the desired band, a pace most people sustain.
  const targetRate = Math.min(maxRate, Math.max(minRate, minRate + (maxRate - minRate) * 0.6));
  const plannedRate = remainingKg === 0 ? 0 : settings.pace === 'timeframe' ? timeframeRate : targetRate;

  const floor = minimumCalories(input.sex);
  const rawKcal = tdee - deficitForKgPerWeek(plannedRate);
  const suggestedKcal = round(Math.max(floor, Math.min(tdee, rawKcal)), 50);

  // Protein: about 1.9 g per kg goal body weight, never below 1.6 g per kg current weight.
  const suggestedProtein = round(Math.max(input.goalWeightKg * 1.9, input.weightKg * 1.6 * 0.97), 5);
  const suggestedFat = round(Math.max((suggestedKcal * 0.27) / 9, input.weightKg * 0.6), 5);
  const suggestedCarbs = Math.max(0, round((suggestedKcal - suggestedProtein * 4 - suggestedFat * 9) / 4, 5));
  const suggestedFiber = Math.max(30, round((suggestedKcal / 1000) * 14, 1));

  const suggested = { kcal: suggestedKcal, protein: suggestedProtein, carbs: suggestedCarbs, fat: suggestedFat, fiber: suggestedFiber };
  const overrides = settings.overrides;
  const activeKcal = overrides.kcal ?? suggested.kcal;
  const activeProtein = overrides.protein ?? suggested.protein;
  const activeFat = overrides.fat ?? (overrides.kcal != null ? round(Math.max((activeKcal * 0.27) / 9, input.weightKg * 0.6), 5) : suggested.fat);
  const activeCarbs = overrides.carbs ?? Math.max(0, round((activeKcal - activeProtein * 4 - activeFat * 9) / 4, 5));
  const active = { kcal: activeKcal, protein: activeProtein, carbs: activeCarbs, fat: activeFat, fiber: overrides.fiber ?? suggested.fiber };

  const dailyDeficit = tdee - active.kcal;
  const expectedKgPerWeek = Math.max(0, kgPerWeekFromDeficit(dailyDeficit));

  if (remainingKg === 0) warnings.push({ code: 'goal_reached', severity: 'info', message: 'Je zit op of onder je streefgewicht. Overweeg onderhoudscalorieën.' });
  if (dailyDeficit > tdee * 0.25) warnings.push({ code: 'aggressive_deficit', severity: 'warning', message: `Een tekort van ${nl(dailyDeficit)} kcal per dag is meer dan 25% van je geschatte verbruik. Dat vergroot de kans op spierverlies, honger en terugval.` });
  if (active.kcal < floor) warnings.push({ code: 'below_minimum', severity: 'warning', message: `Minder dan ${nl(floor)} kcal per dag is zonder begeleiding niet aan te raden.` });
  if (active.kcal < bmr) warnings.push({ code: 'below_bmr', severity: 'warning', message: `Je doel ligt onder je geschatte ruststofwisseling (${nl(bmr)} kcal). Dat is erg streng.` });
  if (expectedKgPerWeek > input.weightKg * 0.01) warnings.push({ code: 'fast_rate', severity: 'warning', message: `Meer dan 1% lichaamsgewicht per week (${nl(expectedKgPerWeek, 2)} kg) is snel. Kies liever 0,25–0,5 kg per week.` });
  if (remainingKg > 0 && timeframeRate < minRate) warnings.push({ code: 'slow_timeframe', severity: 'info', message: `Je tijdspad van ${nl(settings.timeframeMonths)} maanden vraagt maar ${nl(timeframeRate, 2)} kg per week. Met ${nl(active.kcal)} kcal ga je waarschijnlijk sneller.` });
  if (active.protein < input.weightKg * 1.4) warnings.push({ code: 'low_protein', severity: 'warning', message: 'Je eiwitdoel is laag om spiermassa te behouden tijdens afvallen (richtlijn 1,6–2,2 g per kg).' });
  if (overrides.kcal != null && Math.abs(overrides.kcal - suggested.kcal) >= 100) warnings.push({ code: 'override_differs', severity: 'info', message: `Je eigen caloriedoel wijkt ${nl(Math.abs(overrides.kcal - suggested.kcal))} kcal af van de suggestie.` });

  const assumptions = [
    `Ruststofwisseling volgens Mifflin-St Jeor: 10 × ${nl(input.weightKg, 1)} kg + 6,25 × ${nl(input.heightCm)} cm − 5 × ${nl(input.age)} jaar ${input.sex === 'male' ? '+ 5' : '− 161'} = ${nl(bmr)} kcal.`,
    `Dagelijks verbruik = ruststofwisseling × activiteitsfactor ${nl(settings.activityFactor, 2)} = ${nl(tdee)} kcal. Dit is een schatting; je echte verbruik kan 10% hoger of lager liggen.`,
    `1 kg lichaamsgewicht ≈ ${nl(KCAL_PER_KG)} kcal. Een tekort van ${nl(Math.max(0, dailyDeficit))} kcal per dag geeft dus ongeveer ${nl(expectedKgPerWeek, 2)} kg per week.`,
    `Eiwit: ongeveer 1,9 g per kg streefgewicht om spiermassa te beschermen (${nl(active.protein)} g).`,
    'Vet: ongeveer 27% van je calorieën; koolhydraten vullen de rest aan.',
    'Vezels: minstens 30 g per dag. Groente en fruit: 250 g groente en 2 stuks fruit (Schijf van Vijf).',
    'Na 3–4 weken wegen vergelijkt de app je echte trend met deze schatting en past de prognose aan.',
  ];

  return {
    bmr,
    tdee,
    maintenanceRange: [round(tdee * 0.96, 10), round(tdee * 1.04, 10)],
    suggested,
    active,
    vegetablesGrams: 250,
    fruitGrams: 200,
    dailyDeficit,
    expectedKgPerWeek,
    remainingKg,
    forecasts: {
      timeframe: forecastFor(remainingKg, timeframeRate, today),
      target: forecastFor(remainingKg, expectedKgPerWeek, today),
    },
    warnings,
    assumptions,
  };
}

